import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile,rm} from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {pathToFileURL} from 'node:url';
import {exportResource} from '../electron/resources.mjs';
import {DocumentStore} from '../electron/store.mjs';
test('export resource bridge reads bundled styles and owned images, rejecting arbitrary files and active content',async t=>{
  const root = await mkdtemp(path.join(os.tmpdir(),'open-typora-export-'));t.after(()=>rm(root,{recursive:true,force:true}));
  const bundle=path.join(root,'dist'); await mkdir(bundle);
  await writeFile(path.join(bundle,'style.css'),'body{color:black}');await writeFile(path.join(bundle,'script.js'),'alert(1)');
  const outside=path.join(root,'outside.css'); await writeFile(outside,'private');
  const doc=path.join(root,'note.md'),png=path.join(root,'image.png');await writeFile(doc,'# Note');await writeFile(png,Buffer.from([137,80,78,71]));
  const store=new DocumentStore(path.join(root,'session')),record=await store.open(doc);
  const style=await exportResource(pathToFileURL(path.join(bundle,'style.css')).href,store,bundle);
  assert.equal(Buffer.from(style.base64,'base64').toString(),'body{color:black}');assert.equal(style.mime,'text/css');
  const image=await exportResource(`open-typora-asset://local/${record.id}/${encodeURIComponent('image.png')}`,store,bundle);assert.equal(image.mime,'image/png');
  await assert.rejects(exportResource(pathToFileURL(outside).href,store,bundle),/应用目录/);
  await assert.rejects(exportResource(pathToFileURL(path.join(bundle,'script.js')).href,store,bundle),/格式/);
  await assert.rejects(exportResource('open-typora-asset://local/unowned/image.png',store,bundle),/关闭/);
  await assert.rejects(exportResource('javascript:alert(1)',store,bundle),/来源/);
});
